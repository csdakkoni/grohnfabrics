export type Locale = keyof typeof translations;
export type TranslationKey = keyof typeof translations.tr;

// Çeviri helper fonksiyonu
export function t(key: TranslationKey, locale: Locale = 'tr'): string {
  return translations[locale]?.[key] || translations.tr[key] || key;
}

// Hook için kullanılacak context
export function createTranslator(locale: Locale) {
  return (key: TranslationKey): string => t(key, locale);
}
